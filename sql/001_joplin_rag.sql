-- Run once against the existing portfolio database before joplinSync.
-- MariaDB 10.11: JSON arrays are stored as text; no native VECTOR index required.
CREATE TABLE IF NOT EXISTS joplin_document (
    DOCUMENT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    MENU_ID VARCHAR(50) NOT NULL,
    TITLE VARCHAR(255) NOT NULL,
    PATH TEXT NOT NULL,
    MARKDOWN LONGTEXT NOT NULL,
    CONTENT LONGTEXT NOT NULL,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (DOCUMENT_ID),
    UNIQUE KEY uq_joplin_document_menu (MENU_ID),
    CONSTRAINT fk_joplin_document_menu FOREIGN KEY (MENU_ID) REFERENCES admin_menu (MENU_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS joplin_document_chunk (
    DOCUMENT_ID BIGINT UNSIGNED NOT NULL,
    CHUNK_NO INT UNSIGNED NOT NULL,
    CONTENT TEXT NOT NULL,
    EMBEDDING_MODEL VARCHAR(255) NOT NULL,
    EMBEDDING_DIM INT UNSIGNED NOT NULL,
    EMBEDDING JSON NOT NULL,
    PRIMARY KEY (DOCUMENT_ID, CHUNK_NO),
    CONSTRAINT fk_joplin_chunk_document FOREIGN KEY (DOCUMENT_ID) REFERENCES joplin_document (DOCUMENT_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
